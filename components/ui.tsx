// --- Dropdown Menu --- (For table actions)
export const DropdownMenu = ({ children }: { children: React.ReactNode }) => {
    const [isOpen, setIsOpen] = React.useState(false);
    const ref = React.useRef<HTMLDivElement>(null);

    React.useEffect(() => {
        const handleClickOutside = (event: MouseEvent) => {
            if (ref.current && !ref.current.contains(event.target as Node)) {
                setIsOpen(false);
            }
        };
        document.addEventListener("mousedown", handleClickOutside);
        return () => document.removeEventListener("mousedown", handleClickOutside);
    }, []);

    return (
        <div className="relative inline-block text-left" ref={ref}>
            <Button variant="ghost" size="icon" onClick={() => setIsOpen(!isOpen)} className="h-8 w-8">
                <MoreHorizontalIcon className="h-4 w-4" />
            </Button>
            {isOpen && (
                <div
                    className="origin-top-right absolute end-0 mt-2 w-48 rounded-md shadow-lg bg-popover ring-1 ring-black ring-opacity-5 focus:outline-none z-10"
                    role="menu"
                >
                    <div className="py-1" role="none" onClick={() => setIsOpen(false)}>
                        {children}
                    </div>
                </div>
            )}
        </div>
    );
};
export const DropdownMenuItem = ({ children, onClick, className }: { children: React.ReactNode; onClick: () => void; className?: string }) => (
    <button
        onClick={onClick}
        className={cn(
            "w-full text-right px-4 py-2 text-sm text-popover-foreground hover:bg-accent flex items-center gap-2",
            className
        )}
        role="menuitem"
    >
        {children}
    </button>
);
